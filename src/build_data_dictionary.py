"""
build_data_dictionary.py
Step 7 of Module 1: generate docs/data_dictionary.md from the cleaned files.

Run from the project root:
    python src/build_data_dictionary.py
Lists every column of every cleaned table with its dtype, missing count and
distinct count. Human-written descriptions come from the DESCRIPTIONS dict.
"""
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
PROC = ROOT / "data" / "processed"
OUT = ROOT / "docs" / "data_dictionary.md"

TABLE_GRAIN = {
    "customers": "one row per customer_id (one order's customer record)",
    "orders": "one row per order",
    "order_items": "one row per item line within an order",
    "payments": "one row per payment line within an order",
    "payments_by_order": "one row per order that has payments",
    "order_financials": "one row per order (items, freight, payments, revenue)",
    "reviews": "one row per review_id + order_id",
    "order_reviews": "one row per reviewed order (latest review selected)",
    "products": "one row per product",
    "sellers": "one row per seller",
    "geolocation_zip": "one row per zip code prefix (median coordinates)",
    "category_translation": "one row per Portuguese category name",
}

DESCRIPTIONS = {
    "flag_": "Boolean data-quality flag; the original value is left unchanged.",
    "delivery_days": "Days from purchase to customer delivery (delivered orders with a date only).",
    "is_late": "True if customer delivery was after the estimated date (eligible orders only).",
    "revenue": "Sum of item price; missing for canceled/unavailable orders or orders without items.",
    "order_review_score": "Score of the latest review for the order.",
    "category_source": "Where the English category came from: translation_table, manual, or unknown.",
    "product_weight_g_clean": "Weight in grams with 0 treated as missing.",
    "lat_median_raw": "Median latitude before the Brazil bounding-box check.",
    "lng_median_raw": "Median longitude before the Brazil bounding-box check.",
}


def describe(col: str) -> str:
    for key, text in DESCRIPTIONS.items():
        if col == key or (key.endswith("_") and col.startswith(key)):
            return text
    return ""


def main() -> int:
    lines = ["# Data Dictionary (generated)", "",
             "Generated by `src/build_data_dictionary.py` from `data/processed/`. "
             "Do not edit by hand.", ""]
    for table, grain in TABLE_GRAIN.items():
        path = PROC / f"{table}_clean.csv"
        if not path.exists():
            print(f"ERROR: missing {path}. Run src/clean_data.py first.")
            return 1
        df = pd.read_csv(path, dtype={"zip_code_prefix": str,
                                      "customer_zip_code_prefix": str,
                                      "seller_zip_code_prefix": str})
        lines += [f"## {table}", "", f"Grain: {grain}. Rows: {len(df):,}.", "",
                  "| Column | Type | Missing | Distinct | Description |",
                  "|---|---|---|---|---|"]
        for c in df.columns:
            lines.append(f"| {c} | {df[c].dtype} | {int(df[c].isna().sum()):,} | "
                         f"{df[c].nunique():,} | {describe(c)} |")
        lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())